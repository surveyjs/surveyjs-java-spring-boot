-- The tables the integration docs name, in H2 (file mode). Spring Boot runs this at every start
-- (spring.sql.init.mode=always), and SandboxDataSource runs it for each visitor sandbox in demo mode.
--
-- Definitions, responses, progress and presets are JSON documents kept as text, exactly as they arrived: CLOB,
-- never H2's JSON type (its values come back as bytes). created_at is an ISO 8601 UTC string
-- (2026-11-17T13:36:06Z), so `created_at >= ?` compares dates. price and amount are DOUBLE PRECISION, as
-- SQLite's REAL: 4.9 stays 4.9.

CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY,
    key VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    plan VARCHAR(32) DEFAULT 'basic' NOT NULL,
    is_editor BOOLEAN DEFAULT FALSE NOT NULL
);

CREATE TABLE IF NOT EXISTS forms (
    key VARCHAR(255) PRIMARY KEY,
    json CLOB NOT NULL
);

CREATE TABLE IF NOT EXISTS responses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id VARCHAR(255) NOT NULL,
    definition_version VARCHAR(64),
    data CLOB NOT NULL,
    created_at VARCHAR(20) NOT NULL
);
CREATE INDEX IF NOT EXISTS responses_form_id ON responses (form_id, created_at);

CREATE TABLE IF NOT EXISTS progress (
    key VARCHAR(512) PRIMARY KEY,
    json CLOB NOT NULL
);

CREATE TABLE IF NOT EXISTS files (
    id VARCHAR(36) PRIMARY KEY,
    name VARCHAR(1024) NOT NULL,
    type VARCHAR(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS offices (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    region VARCHAR(64) NOT NULL
);
CREATE INDEX IF NOT EXISTS offices_region ON offices (region);

CREATE TABLE IF NOT EXISTS customers (
    email VARCHAR(255) PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS shipping_rates (
    postcode_prefix VARCHAR(16) PRIMARY KEY,
    price DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS claims (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    response_id INTEGER NOT NULL REFERENCES responses (id),
    customer_email VARCHAR(255),
    amount DOUBLE PRECISION
);

CREATE TABLE IF NOT EXISTS variable_presets (
    key VARCHAR(255) PRIMARY KEY,
    json CLOB NOT NULL
);
